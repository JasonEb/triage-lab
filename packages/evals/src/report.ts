import { getScenario } from "@triage/sim";
import type { Style } from "@triage/store";
import type { RunRecord } from "./runner.js";
import type { Score } from "./score.js";

export interface EvalMeta {
  generatedAt: string;
  model: string;
  effort: string;
  maxSteps: number;
  maxTokens: number;
  repeats: number;
  scenarios: number[];
  styles: Style[];
  concurrency: number;
  estimateUsd?: number;
  capUsd: number;
  spentUsd: number;
  apiCalls: number;
  planned: number;
  aborted?: string;
  wallSeconds: number;
  fake?: boolean;
}

export interface EvalResults {
  meta: EvalMeta;
  runs: RunRecord[];
}

export interface Stats {
  mean: number;
  sd: number;
  min: number;
  max: number;
  n: number;
}

/** Mean and sample standard deviation (0 for a single value). */
export function stats(xs: number[]): Stats {
  const n = xs.length;
  if (n === 0) return { mean: NaN, sd: NaN, min: NaN, max: NaN, n };
  const mean = xs.reduce((a, b) => a + b, 0) / n;
  const sd = n > 1 ? Math.sqrt(xs.reduce((a, x) => a + (x - mean) ** 2, 0) / (n - 1)) : 0;
  return { mean, sd, min: Math.min(...xs), max: Math.max(...xs), n };
}

const CHECKS: (keyof Score)[] = ["category", "service", "evidence"];
const allThree = (r: RunRecord) =>
  r.score.category && r.score.service && r.score.evidence ? 1 : 0;

export interface StyleSummary {
  style: Style;
  runs: number;
  /** Accuracy over all runs, with spread across repeats (each repeat = one pass over the scenarios). */
  accuracy: Record<keyof Score | "all", Stats>;
  steps: Stats;
  tokens: Stats;
  costUsd: Stats;
  wallMs: Stats;
}

export function summarizeStyle(runs: RunRecord[], style: Style): StyleSummary {
  const mine = runs.filter((r) => r.style === style);
  const repeats = [...new Set(mine.map((r) => r.repeat))].sort((a, b) => a - b);
  const perRepeat = (f: (r: RunRecord) => number) =>
    stats(
      repeats.map((k) => {
        const rs = mine.filter((r) => r.repeat === k);
        return rs.reduce((a, r) => a + f(r), 0) / rs.length;
      }),
    );
  const acc = Object.fromEntries([
    ...CHECKS.map((c) => [c, perRepeat((r) => r.score[c])]),
    ["all", perRepeat(allThree)],
  ]) as StyleSummary["accuracy"];
  // The headline mean is over all runs; the spread is across repeats.
  for (const [k, s] of Object.entries(acc)) {
    const f = k === "all" ? allThree : (r: RunRecord) => r.score[k as keyof Score];
    s.mean = stats(mine.map(f)).mean;
  }
  return {
    style,
    runs: mine.length,
    accuracy: acc,
    steps: stats(mine.map((r) => r.steps)),
    tokens: stats(mine.map((r) => r.usage.total)),
    costUsd: stats(mine.map((r) => r.costUsd)),
    wallMs: stats(mine.map((r) => r.wallMs)),
  };
}

const pct = (x: number) => (Number.isNaN(x) ? "–" : `${Math.round(x * 100)}%`);
const pctSpread = (s: Stats) => (s.n > 1 ? `${pct(s.mean)} ± ${pct(s.sd)}` : pct(s.mean));
const num = (x: number, digits = 0) =>
  Number.isNaN(x)
    ? "–"
    : x.toLocaleString("en-US", { minimumFractionDigits: digits, maximumFractionDigits: digits });
const meanSd = (s: Stats, digits = 0) =>
  s.n > 1 ? `${num(s.mean, digits)} ± ${num(s.sd, digits)}` : num(s.mean, digits);
const usd = (x: number, digits = 4) => (Number.isNaN(x) ? "–" : `$${x.toFixed(digits)}`);
const kOfN = (xs: number[]) => `${xs.reduce((a, b) => a + b, 0)}/${xs.length}`;

function tally(xs: string[]): string {
  const counts = new Map<string, number>();
  for (const x of xs) counts.set(x, (counts.get(x) ?? 0) + 1);
  return [...counts]
    .sort((a, b) => b[1] - a[1])
    .map(([k, n]) => (n > 1 ? `${k} ×${n}` : k))
    .join(", ");
}

export const ANALYSIS_START = "<!-- analysis:start -->";
export const ANALYSIS_END = "<!-- analysis:end -->";

/** Keep the hand-written analysis from the previous report, if any. */
export function extractAnalysis(previous: string | undefined): string | undefined {
  if (!previous) return undefined;
  const a = previous.indexOf(ANALYSIS_START);
  const b = previous.indexOf(ANALYSIS_END);
  if (a < 0 || b < a) return undefined;
  return previous.slice(a + ANALYSIS_START.length, b).trim();
}

export function renderReport(results: EvalResults, previous?: string): string {
  const { meta, runs } = results;
  const styles = meta.styles;
  const sums = styles.map((s) => summarizeStyle(runs, s));
  const out: string[] = [];

  out.push(
    "# Eval report",
    "",
    "<!-- Generated by `pnpm evals`. Everything outside the Analysis section is regenerated; edit only between the analysis markers. -->",
    "",
    "Does the logging standard make the troubleshooting agent better? Each simulated incident is diagnosed from its **structured** logs and from the same incident's **legacy** logs, several times, and every answer is scored against the scenario's recorded ground truth.",
    "",
  );
  if (meta.fake)
    out.push(
      "> **Fake client run.** These numbers come from the scripted test client, not a model. They only show that the pipeline works.",
      "",
    );
  if (meta.aborted)
    out.push(
      `> **Stopped early:** ${meta.aborted} ${runs.length} of ${meta.planned} planned runs completed.`,
      "",
    );

  out.push("## Headline", "");
  out.push(
    "| Logs | Runs | Root-cause category | Culprit service | Cites relevant line | All three | Steps | Tokens | Cost / run | Wall time / run |",
    "| --- | --: | --: | --: | --: | --: | --: | --: | --: | --: |",
  );
  for (const s of sums)
    out.push(
      `| ${s.style} | ${s.runs} | ${pctSpread(s.accuracy.category)} | ${pctSpread(s.accuracy.service)} | ${pctSpread(s.accuracy.evidence)} | ${pctSpread(s.accuracy.all)} | ${meanSd(s.steps, 1)} | ${meanSd(s.tokens)} | ${usd(s.costUsd.mean)} | ${num(s.wallMs.mean / 1000, 1)}s |`,
    );
  out.push(
    "",
    "Accuracy is the mean over all runs; ± is the standard deviation across repeats (one repeat = one pass over every scenario). Steps, tokens and cost are mean ± standard deviation over runs. Tokens include cache reads and writes.",
    "",
  );

  out.push("## Per scenario", "");
  out.push(
    "| # | Scenario | Logs | Category | Service | Evidence | Steps | Tokens | Cost / run | Answers (category / service) |",
    "| --: | --- | --- | --: | --: | --: | --: | --: | --: | --- |",
  );
  for (const id of meta.scenarios) {
    const sc = getScenario(id);
    for (const style of styles) {
      const rs = runs.filter((r) => r.scenario === id && r.style === style);
      if (rs.length === 0) {
        out.push(`| ${id} | ${sc.title} | ${style} | – | – | – | – | – | – | not run |`);
        continue;
      }
      out.push(
        `| ${id} | ${sc.title} | ${style} | ${kOfN(rs.map((r) => r.score.category))} | ${kOfN(rs.map((r) => r.score.service))} | ${kOfN(rs.map((r) => r.score.evidence))} | ${meanSd(stats(rs.map((r) => r.steps)), 1)} | ${meanSd(stats(rs.map((r) => r.usage.total)))} | ${usd(stats(rs.map((r) => r.costUsd)).mean)} | ${tally(rs.map((r) => (r.outcome === "diagnosed" ? `${r.category} / ${r.service || "?"}` : r.outcome)))} |`,
      );
    }
  }
  out.push("", "Ground truth:", "");
  for (const id of meta.scenarios) {
    const g = getScenario(id).groundTruth;
    out.push(`- **${id}**: ${g.category} in ${g.culpritService} (${g.trigger}). ${g.rootCause}`);
  }
  out.push("");

  out.push("## Analysis", "", ANALYSIS_START);
  out.push(
    extractAnalysis(previous) ??
      "_Not written yet. Read the tables, then replace this paragraph; `pnpm evals` keeps it on the next run._",
  );
  out.push(ANALYSIS_END, "");

  out.push(
    "## Method",
    "",
    "- **Cases:** each scenario in `packages/sim` × {structured, legacy}. Logs are simulated with each scenario's default seed, so every run sees identical data; the only randomness is the model's.",
    "- **Agent:** the same loop, tools, prompt, redaction and budgets as `pnpm triage ask`. The question is the scenario's on-call question, not a hint at the cause.",
    "- **Scoring** (deterministic, `packages/evals/src/score.ts`; no LLM judge):",
    "  - _Root-cause category_: the diagnosis category equals the ground-truth error type. `insufficient_data` never counts.",
    "  - _Culprit service_: the diagnosis service equals the ground-truth service.",
    "  - _Cites relevant line_: at least one cited line, after the agent drops citations it never saw, carries a ground-truth event name or matches a ground-truth pattern.",
    "  - _All three_: all of the above in the same run.",
    "- **Cost** is computed per API call from list prices (`packages/evals/src/cost.ts`) and capped: the run stops once spend reaches the cap.",
    "",
    "## Run",
    "",
    "| Setting | Value |",
    "| --- | --- |",
    `| Model | ${meta.model} |`,
    `| Effort | ${meta.effort} |`,
    `| Budgets per run | ${meta.maxSteps} steps, ${num(meta.maxTokens)} tokens |`,
    `| Repeats | ${meta.repeats} |`,
    `| Runs | ${runs.length} of ${meta.planned} (${meta.apiCalls} API calls, concurrency ${meta.concurrency}) |`,
    ...(meta.estimateUsd !== undefined ? [`| Estimated cost | ${usd(meta.estimateUsd)} |`] : []),
    `| Cost cap | ${usd(meta.capUsd)} |`,
    `| Measured cost | ${usd(meta.spentUsd)} |`,
    `| Wall time | ${num(meta.wallSeconds)}s |`,
    `| Generated | ${meta.generatedAt} |`,
    "",
    "Raw per-run results: [`eval-results.json`](eval-results.json). Regenerate this report from them without API calls: `pnpm evals --report-only`.",
    "",
  );
  return out.join("\n");
}
